export function measurementWarningNl(
  measurement: keyof typeof measurementNamesNl,
  value: number,
  predicted: number,
  unit: "cm" | "kg"
): string {
  const direction = value > predicted ? "hoger" : "lager";
  return `${measurementNamesNl[measurement]} (${value} ${unit}) is meer dan 20% ${direction} dan verwacht bij je lengte (ongeveer ${predicted} ${unit}). Controleer je meting.`;
}

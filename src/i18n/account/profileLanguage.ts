export function profileText(locale: Locale, english: string): string {
  return locale === "nl" ? dutchProfileText[english] ?? english : english;
}

export function measurementValidationText(
  locale: Locale,
  error: string | undefined,
  min: number,
  max: number,
  unit?: string
): string | undefined {
  if (!error || locale !== "nl") return error;
  return `Vul een getal van ${min} tot ${max}${unit ? ` ${unit}` : ""} in.`;
}

